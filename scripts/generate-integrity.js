'use strict';
/**
 * Generates src/_integrity.js with HMAC-SHA256 hashes of all critical server
 * files.  Must be run BEFORE compile-license.js so the hashes are embedded
 * inside the bytecoded integrity.jsc module:
 *
 *   node scripts/generate-integrity.js
 *
 * The SECRET below is the only copy in plaintext; this script is excluded from
 * the packaged ASAR so the secret never ships on customer machines.  The
 * compiled integrity.jsc is the only runtime copy.
 */
const crypto = require('crypto');
const fs     = require('fs');
const path   = require('path');

const ROOT   = path.join(__dirname, '..');
const OUT    = path.join(ROOT, 'src', '_integrity.js');

// ── HMAC secret — never change after first release (would fail existing installs) ──
const SECRET = 'z9K2mNpQw7xL4vR8Y6bTcHdEfGiJuAoB3e1sF0nCrWjMkXhUyDqPaIlVtZgOv5w';

// ── Files whose integrity matters most ───────────────────────────────────────
// Re-hashed at startup inside integrity.jsc.  Patch any of these and the app
// refuses to run.
const TARGETS = [
    'server/index.js',               // license middleware wiring
    'server/routes/campaigns.js',    // campaign route handlers
    'server/services/campaignService.js', // actual message dispatch
    'src/whatsapp.js',               // WhatsApp send primitives
];

const hashes = {};
for (const rel of TARGETS) {
    const abs = path.join(ROOT, rel);
    if (!fs.existsSync(abs)) {
        console.error(`[generate-integrity] ✗ Missing target file: ${rel}`);
        process.exit(1);
    }
    const content = fs.readFileSync(abs);
    hashes[rel] = crypto.createHmac('sha256', SECRET).update(content).digest('hex');
    console.log(`[generate-integrity] ✓ hashed ${rel}`);
}

// ── Write src/_integrity.js ───────────────────────────────────────────────────
const src = `'use strict';
// AUTO-GENERATED by scripts/generate-integrity.js — DO NOT EDIT BY HAND
// Compiled to src/integrity.jsc — see compile-license.js
const crypto = require('crypto');
const fs     = require('fs');
const path   = require('path');

const SECRET   = ${JSON.stringify(SECRET)};
const ROOT     = path.join(__dirname, '..');
const EXPECTED = ${JSON.stringify(hashes, null, 4)};

function verify() {
    for (const [rel, expected] of Object.entries(EXPECTED)) {
        try {
            const content = fs.readFileSync(path.join(ROOT, rel));
            const actual  = crypto.createHmac('sha256', SECRET).update(content).digest('hex');
            if (actual !== expected) {
                console.error('[Zyqora] Integrity mismatch:', rel);
                return false;
            }
        } catch (_) {
            console.error('[Zyqora] Integrity read error:', rel);
            return false;
        }
    }
    return true;
}

module.exports = { verify };
`;

fs.writeFileSync(OUT, src, 'utf8');
console.log(`[generate-integrity] ✓ wrote src/_integrity.js (${Object.keys(hashes).length} hashes)`);
process.exit(0);
